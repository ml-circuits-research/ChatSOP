#!/usr/bin/env node
/** (Under audit/ because it reads sealed test inputs: eval/leakage.mjs SEALED_AUDITORS.) One-off repair of the archived corpora that `node check-datasets.mjs --archive` reported red (TODO 1e, 2026-10-01).
 * Data is fixed, never the verifier. Idempotent: a second run finds nothing to change.
 *
 *   - clean-english: the train row whose message a sealed wild test row repeats (`wild_we_053` = `fv1_003480_0`) leaves train; the sealed test is not edited.
 *   - proofing: hard_cases rows take the split of their split group; ro_translated rows with an empty input and rows whose input repeats a sealed
 *     test input are dropped (a row that duplicates a sealed input leaves train and dev); in train and dev a row whose input repeats an earlier row's
 *     input (the corpus audit's duplicate_question invariant) is dropped, the first one stays. The training projection is regenerated by the caller
 *     (`tools/research/build-proofreader-projection.mjs`).
 *
 *   node tools/datasets/audit/fix-archive-defects.mjs [--apply]
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {fileURLToPath} from 'node:url';
import {readJsonlShardedSync, writeJsonlShardedSync, hashJsonlSharded} from '../../../lib/jsonl-shards.mjs';
import {corpusDir, resolveDatasetPath} from '../../../lib/dataset-paths.mjs';

const ROOT = fileURLToPath(new URL('../../../', import.meta.url));
const norm = text => String(text ?? '').normalize('NFKC').toLowerCase().replace(/[^\p{L}\p{N}]+/gu, ' ').trim();
const apply = process.argv.includes('--apply');
const rel = file => path.join(ROOT, resolveDatasetPath(file));
const report = [];

// ---- clean-english
{
  const dir = path.join(ROOT, corpusDir('clean-english'));
  const test = readJsonlShardedSync(path.join(ROOT, 'eval/suites/clean-english/test.jsonl'));
  const sealed = new Set(test.map(row => norm(row.question)));
  for (const split of ['train', 'dev']) {
    const file = path.join(dir, split + '.jsonl');
    const rows = readJsonlShardedSync(file);
    const keep = rows.filter(row => !sealed.has(norm(row.question)));
    for (const row of rows) if (!keep.includes(row)) report.push(`clean-english ${split}: drop ${row.id} (${JSON.stringify(row.question)} repeats a sealed test message)`);
    if (apply && keep.length !== rows.length) writeJsonlShardedSync(file, keep);
  }
}
// ---- proofing
{
  const dir = path.join(ROOT, corpusDir('proofing'));
  const read = name => readJsonlShardedSync(path.join(dir, name + '.jsonl'));
  const test = readJsonlShardedSync(path.join(ROOT, 'eval/suites/proofing/test.jsonl'));
  const sealed = new Set(test.map(row => norm(row.input)));
  const groupSplit = new Map();
  for (const name of ['train', 'dev']) for (const row of read(name)) groupSplit.set(row.split_group_id, name);
  for (const row of test) groupSplit.set(row.split_group_id, 'test');
  const hard = read('hard_cases');
  for (const row of hard) {
    const want = groupSplit.get(row.split_group_id);
    if (row.split != null && want && row.split !== want) { report.push(`proofing hard_cases: ${row.id} split ${row.split} -> ${want}`); row.split = want; }
  }
  if (apply) writeJsonlShardedSync(path.join(dir, 'hard_cases.jsonl'), hard);
  for (const name of ['train', 'dev']) {
    const rows = read(name), seen = new Set();
    const keepRows = rows.filter(row => {
      const key = norm(row.input);
      if (seen.has(key)) { report.push(`proofing ${name}: drop ${row.id} (input repeats an earlier row of the split)`); return false; }
      seen.add(key);
      return true;
    });
    if (apply && keepRows.length !== rows.length) writeJsonlShardedSync(path.join(dir, name + '.jsonl'), keepRows);
  }
  const ro = read('ro_translated');
  const keep = ro.filter(row => {
    if (!String(row.input ?? '').trim()) { report.push(`proofing ro_translated: drop ${row.id} (empty input)`); return false; }
    if (sealed.has(norm(row.input))) { report.push(`proofing ro_translated: drop ${row.id} (input repeats a sealed test input)`); return false; }
    return true;
  });
  if (apply && keep.length !== ro.length) writeJsonlShardedSync(path.join(dir, 'ro_translated.jsonl'), keep);
}
// ---- manifest and VERSION of a corpus whose rows changed: file hashes refreshed, the repair recorded, the build counter advanced
async function refreshManifest(corpus, note) {
  const dir = path.join(ROOT, corpusDir(corpus));
  const manifestFile = path.join(dir, 'manifest.json'), versionFile = path.join(dir, 'VERSION');
  const manifest = JSON.parse(fs.readFileSync(manifestFile, 'utf8'));
  for (const key of Object.keys(manifest.sha256 ?? {})) manifest.sha256[key] = await hashJsonlSharded(path.join(ROOT, resolveDatasetPath(key)));
  manifest.repairs = [...(manifest.repairs ?? []), note];
  fs.writeFileSync(manifestFile, JSON.stringify(manifest, null, 1) + '\n');
  const previous = JSON.parse(fs.readFileSync(versionFile, 'utf8'));
  const counter = previous.counter + 1;
  const version = {...previous, counter, label: `${corpus} build ${counter} (${note.replace(/^\d{4}-\d{2}-\d{2} [\w-]+ \(build \d+\): /, '')})`, manifest_sha256: crypto.createHash('sha256').update(fs.readFileSync(manifestFile)).digest('hex')};
  fs.writeFileSync(versionFile, JSON.stringify(version, null, 1) + '\n');
}
// A run that dropped rows records them itself; `--refresh-manifest "<note>"` refreshes the hashes and records the note after an earlier run.
const dropped = report.filter(line => /^proofing (train|dev)/.test(line)).map(line => line.split(' ')[3]);
const noteIndex = process.argv.indexOf('--refresh-manifest');
const buildOf = () => JSON.parse(fs.readFileSync(path.join(ROOT, corpusDir('proofing'), 'VERSION'), 'utf8')).counter + 1;
if (apply && (dropped.length || noteIndex >= 0)) {
  const what = noteIndex >= 0 ? process.argv[noteIndex + 1] : `train/dev rows whose input repeats an earlier row of the split dropped (${dropped.join(', ')}); projection regenerated`;
  await refreshManifest('proofing', `2026-10-01 arch-findings-agent (build ${buildOf()}): ${what} (tools/datasets/audit/fix-archive-defects.mjs)`);
}
console.log(report.join('\n') || 'nothing to change');
console.log(apply ? 'applied' : 'dry run (use --apply)');
