#!/usr/bin/env node
/** Flat training projection for the `proofreader` role (DS007, DS021 message-only input).
 *
 * Flattens datasets/<corpus>/{train,dev}.jsonl (the direct English/Romanian-source-but-English-target arm) and
 * datasets/<corpus>/ro_translated.jsonl (the Romanian-source translate arm, split by its own `split` field, if the
 * file exists) into datasets/<corpus>/proofreader/{train,dev}.jsonl: one row per source row,
 * {id, prompt, target, kind, language, source_language, pipeline, target_source}, matching
 * training/python/common.py chat_ids() (the user's raw message, no instruction wrapper, no system role). Only
 * kind identity/repair rows with a non-null target are included; hard_cases.jsonl and any row with target === null
 * are never emitted. Rewrites datasets/<corpus>/proofreader/manifest.json with fresh row counts and file hashes.
 *
 * This is the checked-in version of the ad hoc flattening step that first produced
 * datasets_archive/proofing/proofreader/{train,dev}.jsonl (status/journal.jsonl 2026-09-29T22:03/22:24Z); running it again
 * on the unchanged v1 rows must reproduce byte-identical output (verified by the caller before trusting a v2 diff).
 *
 *   node tools/research/build-proofreader-projection.mjs [--corpus proofing]
 */
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import {readJsonlShardedSync} from '../../lib/jsonl-shards.mjs';
import {corpusDir} from '../../lib/dataset-paths.mjs';

const ROOT = fileURLToPath(new URL('../../', import.meta.url));
const sha256 = text => createHash('sha256').update(text).digest('hex');
const writeJsonl = (file, rows) => { fs.mkdirSync(path.dirname(file), {recursive: true}); fs.writeFileSync(file, rows.map(r => JSON.stringify(r)).join('\n') + (rows.length ? '\n' : '')); };

function flatten(rows, {pipeline} = {}) {
  return rows.filter(r => (r.kind === 'identity' || r.kind === 'repair') && r.target != null).map(r => ({
    id: r.id, prompt: r.input, target: r.target, kind: r.kind, language: r.language,
    source_language: r.source_language ?? r.language, pipeline: pipeline ?? r.pipeline ?? 'direct', target_source: r.target_source ?? null,
  }));
}

function main() {
  const args = process.argv.slice(2);
  const opt = name => { const i = args.indexOf('--' + name); return i < 0 ? null : args[i + 1]; };
  const corpus = opt('corpus') ?? 'proofing';
  const dir = path.join(ROOT, corpusDir(corpus));
  const roFile = path.join(dir, 'ro_translated.jsonl');
  const roRows = fs.existsSync(roFile) ? readJsonlShardedSync(roFile) : [];

  const out = {};
  for (const split of ['train', 'dev']) {
    const direct = flatten(readJsonlShardedSync(path.join(dir, split + '.jsonl')), {pipeline: 'direct'});
    const ro = flatten(roRows.filter(r => r.split === split));
    out[split] = [...direct, ...ro];
  }

  const projDir = path.join(dir, 'proofreader');
  const files = {};
  for (const split of ['train', 'dev']) {
    const file = path.join(projDir, split + '.jsonl');
    writeJsonl(file, out[split]);
    files[`${corpusDir(corpus)}/proofreader/${split}.jsonl`] = {rows: out[split].length, sha256: sha256(fs.readFileSync(file, 'utf8'))};
  }
  const byKind = split => Object.fromEntries(['identity', 'repair'].map(k => [k, out[split].filter(r => r.kind === k).length]));
  const byPipeline = split => Object.fromEntries(['direct', 'translate'].map(p => [p, out[split].filter(r => r.pipeline === p).length]));
  const manifest = {
    format: 'chatsop-proofreader-projection-v1', corpus, prompt_profile: 'message-only',
    prompt: "row.prompt verbatim: the raw text (the formalizer-v1 message, or its SymbolicLM English translation for pipeline=translate rows) and nothing else, matching training/python/common.py chat_ids() (DS021 message-only input, no instruction wrapper, no system role)",
    target: 'row.target verbatim: the proofread/repaired English text, or the identical input for kind=identity rows',
    created: new Date().toISOString().slice(0, 10), training_authorized: false, review_status: 'not_reviewed',
    note: `Generated by tools/research/build-proofreader-projection.mjs from datasets/${corpus}/{train,dev}.jsonl and ro_translated.jsonl (if present); only kind identity/repair rows with a non-null target are included (never hard).`,
    files, by_kind: {train: byKind('train'), dev: byKind('dev')}, by_pipeline: {train: byPipeline('train'), dev: byPipeline('dev')},
  };
  fs.writeFileSync(path.join(projDir, 'manifest.json'), JSON.stringify(manifest, null, 1) + '\n');
  console.log(JSON.stringify({train: out.train.length, dev: out.dev.length, by_kind: manifest.by_kind, by_pipeline: manifest.by_pipeline}, null, 1));
}
main();
